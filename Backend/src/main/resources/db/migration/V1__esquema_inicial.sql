-- HU-02 · Initial schema. Mirrors the JPA entities; Hibernate runs with ddl-auto=validate.
-- Never edit an applied migration: add a new V<n>__*.sql instead.

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    email       VARCHAR(255) NOT NULL UNIQUE,
    password    VARCHAR(255) NOT NULL,
    role        VARCHAR(20)  NOT NULL CHECK (role IN ('USER', 'ADMIN')),
    created_at  TIMESTAMP(6) NOT NULL
);

CREATE TABLE categories (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL UNIQUE,
    description  VARCHAR(255)
);

CREATE TABLE state (
    id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE city (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state_id  INTEGER      NOT NULL REFERENCES state (id),
    name      VARCHAR(255) NOT NULL,
    UNIQUE (state_id, name)
);

CREATE TABLE products (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255)   NOT NULL,
    description  VARCHAR(1000),
    price        NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    stock        INTEGER        NOT NULL CHECK (stock >= 0),
    category_id  BIGINT         NOT NULL REFERENCES categories (id),
    created_by   BIGINT         REFERENCES users (id),
    active       BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMP(6)   NOT NULL,
    image_url    VARCHAR(500)
);

CREATE TABLE address (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  VARCHAR(255) NOT NULL,
    last_name   VARCHAR(255) NOT NULL,
    address     VARCHAR(255) NOT NULL,
    city_id     INTEGER      NOT NULL REFERENCES city (id),
    zip_code    VARCHAR(255) NOT NULL,
    created_by  BIGINT       NOT NULL REFERENCES users (id)
);

CREATE TABLE orders (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6)   NOT NULL,
    user_id     BIGINT         NOT NULL REFERENCES users (id),
    total       NUMERIC(12, 2) NOT NULL CHECK (total >= 0),
    address_id  BIGINT         NOT NULL REFERENCES address (id),
    status      VARCHAR(20)    NOT NULL DEFAULT 'PENDIENTE_PAGO'
                CHECK (status IN ('PENDIENTE_PAGO', 'PAGADA', 'ENVIADA', 'ENTREGADA', 'CANCELADA')),
    -- Until when an unpaid order holds its stock (HU-17/HU-18).
    expires_at  TIMESTAMP(6)
);

CREATE TABLE order_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT         NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id  BIGINT         NOT NULL REFERENCES products (id),
    quantity    INTEGER        NOT NULL CHECK (quantity > 0),
    unit_price  NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0)
);

CREATE TABLE wishlist (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    product_id  BIGINT       NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    created_at  TIMESTAMP(6) NOT NULL,
    UNIQUE (user_id, product_id)
);

-- Catalog listing filters by active + category (HU-10).
CREATE INDEX idx_products_active_category ON products (active, category_id);
-- "Mis pedidos", newest first (HU-19).
CREATE INDEX idx_orders_user_created ON orders (user_id, created_at DESC);
-- Job that cancels expired unpaid orders (HU-18).
CREATE INDEX idx_orders_status_expires ON orders (status, expires_at);
CREATE INDEX idx_order_items_order ON order_items (order_id);
